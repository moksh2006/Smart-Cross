import React, { useEffect, useState } from 'react';
import { BarChart, Bar, LineChart, Line, XAxis, YAxis, Tooltip, CartesianGrid, ResponsiveContainer, Legend } from 'recharts';
import { BarChart3 } from 'lucide-react';
import { useLiveData } from '../context/LiveDataContext';
import { Panel, DataKindBadge, Empty, Spinner, ErrorBox, inputCls } from '../components/ui';
import { api } from '../lib/api';
import { SOURCE_META } from '../lib/constants';
import { fmtDuration, fmtTime } from '../lib/format';

const COLORS = { 19: '#38bdf8', 20: '#a78bfa', 23: '#f59e0b', 24: '#10b981' };
const axis = { stroke: '#64748b', fontSize: 11 };
const tip = { contentStyle: { background: '#0f172a', border: '1px solid #334155', borderRadius: 8, fontSize: 12 } };

function byHourPivot(rows, valueKey) {
  const hours = Array.from({ length: 24 }, (_, h) => ({ hour: `${String(h).padStart(2, '0')}h` }));
  for (const r of rows) hours[r.hour][r.phatakNumber] = (hours[r.hour][r.phatakNumber] || 0) + r[valueKey];
  return hours;
}

function Section({ title, kind, description, children, className = '' }) {
  return (
    <Panel title={title} className={className} actions={<DataKindBadge kind={kind} />}>
      {description && <p className="-mt-1 mb-3 text-xs text-slate-500">{description}</p>}
      {children}
    </Panel>
  );
}

export default function AnalyticsPage() {
  const { mode: currentMode } = useLiveData();
  const [days, setDays] = useState(7);
  const [mode, setMode] = useState(currentMode || 'LIVE');
  const [data, setData] = useState(null);
  const [error, setError] = useState(null);

  useEffect(() => { if (currentMode) setMode(currentMode); }, [currentMode]);
  useEffect(() => {
    setData(null);
    api.analytics({ days, mode }).then(setData).catch((e) => setError(e.message));
  }, [days, mode]);

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-end justify-between gap-3">
        <div><h1 className="text-2xl font-bold">Historical analytics</h1><p className="text-sm text-slate-400">Each chart states whether it shows <b>recorded</b> observations, <b>predicted</b> states or <b>estimated</b> values.</p></div>
        <div className="flex gap-2">
          <select className={`${inputCls} w-auto`} value={mode} onChange={(e) => setMode(e.target.value)} aria-label="Data mode"><option value="LIVE">Live data</option><option value="SIMULATION">Simulated data</option></select>
          <select className={`${inputCls} w-auto`} value={days} onChange={(e) => setDays(Number(e.target.value))} aria-label="Period"><option value={1}>24 h</option><option value={7}>7 days</option><option value={30}>30 days</option><option value={90}>90 days</option></select>
        </div>
      </div>
      {mode === 'SIMULATION' && <div className="rounded-lg border border-fuchsia-500/40 bg-fuchsia-500/10 p-2 text-sm text-fuchsia-200">You are viewing statistics generated by simulated trains. They do not describe real railway traffic.</div>}
      <ErrorBox error={error} />
      {!data ? <Spinner /> : (
        <div className="grid gap-4 lg:grid-cols-2">
          <Section title="Train frequency" kind={data.trainFrequency.dataKind} description={data.trainFrequency.description}>
            {data.trainFrequency.byDay.length === 0 ? <Empty>No observed passages in this period.</Empty> : (
              <ResponsiveContainer width="100%" height={220}><BarChart data={data.trainFrequency.byDay}><CartesianGrid stroke="#1e293b" /><XAxis dataKey="day" tick={axis} /><YAxis allowDecimals={false} tick={axis} /><Tooltip {...tip} /><Bar dataKey="trains" fill="#38bdf8" name="Trains" /></BarChart></ResponsiveContainer>
            )}
          </Section>
          <Section title="Passages by hour (IST)" kind={data.trainFrequency.dataKind} description="Observed crossing passages per hour of day">
            {data.trainFrequency.byHour.length === 0 ? <Empty>No observed passages.</Empty> : (
              <ResponsiveContainer width="100%" height={220}><BarChart data={byHourPivot(data.trainFrequency.byHour, 'passages')}><CartesianGrid stroke="#1e293b" /><XAxis dataKey="hour" tick={axis} interval={2} /><YAxis allowDecimals={false} tick={axis} /><Tooltip {...tip} /><Legend />{[19, 20, 23, 24].map((n) => <Bar key={n} dataKey={n} stackId="a" fill={COLORS[n]} name={`Phatak ${n}`} />)}</BarChart></ResponsiveContainer>
            )}
          </Section>
          <Section title="Average speed & delay by train" kind={data.averageSpeed.dataKind} description={data.averageSpeed.description}>
            {data.averageSpeed.byTrain.length === 0 ? <Empty>No speed observations.</Empty> : (
              <table className="w-full text-sm"><thead className="text-left text-xs text-slate-500"><tr><th>Train</th><th>Avg speed</th><th>Avg delay</th><th>Passages</th></tr></thead>
                <tbody>{data.averageSpeed.byTrain.map((r) => <tr key={r.trainNumber} className="border-t border-white/5"><td className="py-1">{r.trainNumber}</td><td>{r.avgSpeedKmh} km/h</td><td>{r.avgDelayMinutes ?? '—'} min</td><td>{r.passages}</td></tr>)}</tbody></table>
            )}
          </Section>
          <Section title="Average crossing waiting time" kind="ESTIMATED" description="Estimated closure duration per passage (model) and average duration of predicted CLOSED states">
            {data.waitingTime.estimated.byPhatak.length === 0 && data.waitingTime.predictedState.byPhatak.length === 0 ? <Empty>No data.</Empty> : (
              <table className="w-full text-sm"><thead className="text-left text-xs text-slate-500"><tr><th>Phatak</th><th>Estimated closure <DataKindBadge kind="ESTIMATED" /></th><th>Predicted CLOSED duration <DataKindBadge kind="PREDICTED" /></th></tr></thead>
                <tbody>{[19, 20, 23, 24].map((n) => { const e = data.waitingTime.estimated.byPhatak.find((x) => x.phatakNumber === n); const p = data.waitingTime.predictedState.byPhatak.find((x) => x.phatakNumber === n); return <tr key={n} className="border-t border-white/5"><td className="py-1">{n}</td><td>{e ? `${fmtDuration(e.avgSeconds)} (n=${e.samples})` : '—'}</td><td>{p ? `${fmtDuration(p.avgSeconds)} (n=${p.samples})` : '—'}</td></tr>; })}</tbody></table>
            )}
          </Section>
          <Section title="Prediction error by horizon" kind={data.predictionAccuracy.dataKind} description={data.predictionAccuracy.description}>
            {data.predictionAccuracy.byHorizon.length === 0 ? <Empty>No evaluated predictions yet (needs observed passages).</Empty> : (
              <ResponsiveContainer width="100%" height={220}><BarChart data={data.predictionAccuracy.byHorizon.map((r) => ({ ...r, h: `${r.horizonMinutes} min before` }))}><CartesianGrid stroke="#1e293b" /><XAxis dataKey="h" tick={axis} /><YAxis tick={axis} unit="s" /><Tooltip {...tip} /><Legend /><Bar dataKey="maeSeconds" fill="#f59e0b" name="Mean absolute error (s)" /><Bar dataKey="biasSeconds" fill="#64748b" name="Bias (s)" /></BarChart></ResponsiveContainer>
            )}
          </Section>
          <Section title="Predicted vs observed arrival" kind={data.predictionAccuracy.dataKind} description="Most recent evaluated predictions">
            {data.predictionAccuracy.recent.length === 0 ? <Empty>No evaluations.</Empty> : (
              <div className="max-h-56 overflow-y-auto"><table className="w-full text-xs"><thead className="text-left text-slate-500"><tr><th>Train</th><th>Phatak</th><th>Horizon</th><th>Predicted</th><th>Observed</th><th>Error</th><th>Source</th></tr></thead>
                <tbody>{data.predictionAccuracy.recent.map((r, i) => <tr key={i} className="border-t border-white/5"><td className="py-1">{r.trainNumber}</td><td>{r.phatakNumber}</td><td>{r.horizonMinutes}m</td><td>{fmtTime(r.predictedArrival, true)}</td><td>{fmtTime(r.observedArrival, true)}</td><td className={Math.abs(r.errorSeconds) > 120 ? 'text-rose-300' : 'text-emerald-300'}>{r.errorSeconds > 0 ? '+' : ''}{r.errorSeconds}s</td><td>{SOURCE_META[r.source]?.short}</td></tr>)}</tbody></table></div>
            )}
          </Section>
          <Section title="Predicted closure patterns (IST)" kind={data.closurePatterns.dataKind} description={data.closurePatterns.description}>
            {data.closurePatterns.byHour.length === 0 ? <Empty>No predicted closures.</Empty> : (
              <ResponsiveContainer width="100%" height={220}><LineChart data={byHourPivot(data.closurePatterns.byHour, 'closures')}><CartesianGrid stroke="#1e293b" /><XAxis dataKey="hour" tick={axis} interval={2} /><YAxis allowDecimals={false} tick={axis} /><Tooltip {...tip} /><Legend />{[19, 20, 23, 24].map((n) => <Line key={n} dataKey={n} stroke={COLORS[n]} dot={false} name={`Phatak ${n}`} />)}</LineChart></ResponsiveContainer>
            )}
          </Section>
          <Section title="Prediction source distribution" kind={data.sourceDistribution.dataKind} description={data.sourceDistribution.description}>
            {data.sourceDistribution.predictions.length === 0 && data.sourceDistribution.gateTransitions.length === 0 ? <Empty>No data.</Empty> : (
              <ResponsiveContainer width="100%" height={220}>
                <BarChart layout="vertical" data={Object.keys(SOURCE_META).filter((k) => k !== 'UNKNOWN').map((k) => ({ source: SOURCE_META[k].short, predictions: (data.sourceDistribution.predictions.find((x) => x.source === k) || {}).count || 0, transitions: (data.sourceDistribution.gateTransitions.find((x) => x.source === k) || {}).count || 0 }))}>
                  <CartesianGrid stroke="#1e293b" /><XAxis type="number" tick={axis} allowDecimals={false} /><YAxis type="category" dataKey="source" tick={axis} width={120} /><Tooltip {...tip} /><Legend /><Bar dataKey="predictions" fill="#38bdf8" name="Logged predictions" /><Bar dataKey="transitions" fill="#a78bfa" name="Gate transitions" />
                </BarChart>
              </ResponsiveContainer>
            )}
          </Section>
          <Section title="RailRadar API usage" kind={data.apiUsage.dataKind} description={data.apiUsage.description} className="lg:col-span-2">
            {data.apiUsage.byDay.length === 0 ? <Empty>No API calls in this period.</Empty> : (
              <div className="grid gap-4 md:grid-cols-3">
                <div className="md:col-span-2"><ResponsiveContainer width="100%" height={200}><BarChart data={data.apiUsage.byDay}><CartesianGrid stroke="#1e293b" /><XAxis dataKey="day" tick={axis} /><YAxis allowDecimals={false} tick={axis} /><Tooltip {...tip} /><Legend /><Bar dataKey="calls" fill="#38bdf8" name="Calls" /><Bar dataKey="failures" fill="#ef4444" name="Failures" /></BarChart></ResponsiveContainer></div>
                <table className="text-xs"><thead className="text-left text-slate-500"><tr><th>HTTP</th><th>Error</th><th>Calls</th></tr></thead><tbody>{data.apiUsage.byStatus.map((r, i) => <tr key={i} className="border-t border-white/5"><td className="py-1">{r.httpStatus ?? '—'}</td><td>{r.errorCode || 'OK'}</td><td>{r.calls}</td></tr>)}</tbody></table>
              </div>
            )}
          </Section>
        </div>
      )}
      <p className="flex items-center gap-1 text-xs text-slate-500"><BarChart3 className="w-3.5 h-3.5" />Generated {data ? fmtTime(data.generatedAt, true) : '—'} · period {days} day(s) · {mode === 'LIVE' ? 'live' : 'simulated'} records only.</p>
    </div>
  );
}
